/// Meaning of [number] in [languageCode].
///
/// Meanings live outside [AsmaulHusna] because they are the only localized
/// field; the Arabic and its transliteration are language-neutral.
String asmaulMeaning(int number, String languageCode) {
  final localized = languageCode.startsWith('en')
      ? asmaulMeaningEn[number]
      : asmaulMeaningId[number];
  return localized ?? asmaulMeaningId[number] ?? '';
}

